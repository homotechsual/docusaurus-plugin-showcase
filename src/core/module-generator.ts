import type { ShowcaseItem, ShowcasePageData } from './types.js'

function serializeItem(item: ShowcaseItem): string {
  const { _localImagePath, preview, ...rest } = item as ShowcaseItem & { _localImagePath?: string }
  const previewJs = _localImagePath
    ? `(function(m){return typeof m==='string'?m:(m&&m.default)||m})(require(${JSON.stringify(_localImagePath.replace(/\\/g, '/'))}))`
    : JSON.stringify(preview ?? null)
  const inner = JSON.stringify(rest).slice(1, -1)
  return inner ? `{"preview":${previewJs},${inner}}` : `{"preview":${previewJs}}`
}

export function generateShowcaseModule(data: ShowcasePageData): string {
  const itemsJs = data.items.map(serializeItem).join(',')
  const { computedFields, ...options } = data.options
  const fieldsJs = Object.entries(computedFields ?? {}).map(([key, field]) => {
    const { resolver, ...definition } = field
    if (typeof resolver === 'function') {
      throw new Error('[docusaurus-plugin-showcase] Cannot serialize a computed resolver function; use a module reference.')
    }
    return `${JSON.stringify(key)}:{...${JSON.stringify(definition)},resolver:require(${JSON.stringify(resolver.module.replace(/\\/g, '/'))})[${JSON.stringify(resolver.exportName)}]}`
  }).join(',')
  return (
    `// @generated by @homotechsual/docusaurus-plugin-showcase\n` +
    `module.exports = {"items":[${itemsJs}],"options":{...${JSON.stringify(options)},computedFields:{${fieldsJs}}}};\n`
  )
}
